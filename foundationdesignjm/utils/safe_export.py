"""Exporter to CSI SAFE .s2k text format.

SAFE / SAP2000 use a tabular text format with sections like:

    TABLE:  "PROGRAM CONTROL"
       ProgramName=SAFE  Version="20.0.0"  ProgLevel=Post-Tensioning

    TABLE:  "POINT OBJECT CONNECTIVITY"
       Point=1  X=0.0  Y=0.0  Z=0.0
       Point=2  X=1.0  Y=0.0  Z=0.0
       ...

The export here is intentionally minimal (geometry, springs and loads) so
that the model opens in SAFE as a starting point. It is NOT a complete
round-trip — slabs, ties, post-tensioning etc. must be assigned in SAFE
afterwards.

Reference: CSI Open Application Programming Interface and Database
documentation (publicly available with the SAFE installation).
"""

from __future__ import annotations

import os
from typing import TYPE_CHECKING, List, Optional, TextIO

if TYPE_CHECKING:
    from ..analysis.mat_foundation import MatFoundationSolver, MatResult

from .._brand import SLUG as _BRAND_SLUG


_HEADER = f"$ File C:\\... generated by {_BRAND_SLUG}"


def _write_section(fh: TextIO, title: str, rows: List[str]) -> None:
    fh.write(f'\nTABLE:  "{title}"\n')
    for r in rows:
        fh.write(f"   {r}\n")


def export_safe_s2k(
    *,
    nodes_xy,
    elements,
    column_loads,
    uniform_pressure: float,
    thickness: float,
    fck_MPa: float,
    k_s_kN_m3: float,
    output_path: str,
    model_name: str = "Mat",
) -> str:
    """Write a minimal SAFE .s2k file.

    Args:
        nodes_xy: (N, 2) array of node (x, y) coordinates in metres.
        elements: (M, 4) array of node indices (0-based, ccw).
        column_loads: iterable of (x, y, P, Mx, My, name) tuples.
        uniform_pressure: distributed downwards pressure in kN/m^2.
        thickness: slab thickness in metres.
        fck_MPa: concrete characteristic strength in MPa.
        k_s_kN_m3: subgrade reaction in kN/m^3 (assigned as surface spring).
        output_path: file path to write the .s2k.
        model_name: title for the SAFE model.

    Returns:
        The output_path (absolute).
    """
    output_path = os.path.abspath(output_path)
    os.makedirs(os.path.dirname(output_path) or ".", exist_ok=True)

    with open(output_path, "w", encoding="utf-8") as fh:
        fh.write(f"$ {model_name} - generated by {_BRAND_SLUG}\n")
        fh.write("$ Units: kN, m, C\n\n")

        # Program control
        _write_section(fh, "PROGRAM CONTROL", [
            'ProgramName="SAFE"   Version="20.0.0"   ProgLevel="Reinforced"'
            '   CurrUnits="kN, m, C"   SteelCode="Eurocode 2-2004"'
            '   ConcCode="Eurocode 2-2004"',
        ])

        # Concrete material
        E_concrete = 22000.0 * ((fck_MPa + 8.0) / 10.0) ** 0.3  # MPa, EC2 (3.1.2)
        E_concrete *= 1000.0  # MPa → kN/m^2
        _write_section(fh, "MATERIAL PROPERTIES 01 - GENERAL", [
            f'Material="CONC"   Type="Concrete"   Grade="EC2 C{int(fck_MPa)}/37"'
            f'   UnitWeight=25   E={E_concrete:.1f}   U=0.20',
        ])

        # Slab section property
        _write_section(fh, "SLAB PROPERTIES", [
            f'Slab="MAT"   Type="Mat"   MatProp="CONC"   Thickness={thickness}',
        ])

        # Soil surface spring
        _write_section(fh, "SOIL SUBGRADE PROPERTIES", [
            f'SoilProp="SOIL"   Subgrade={k_s_kN_m3}',
        ])

        # Point coordinates
        pt_rows = []
        for i, (x, y) in enumerate(nodes_xy):
            pt_rows.append(f'Point={i + 1}   X={x:.4f}   Y={y:.4f}   Z=0')
        _write_section(fh, "POINT COORDINATES", pt_rows)

        # Area connectivity
        area_rows = []
        for j, conn in enumerate(elements):
            n0, n1, n2, n3 = (int(c) + 1 for c in conn)
            area_rows.append(
                f'Area={j + 1}   NumPoints=4   Point1={n0}   Point2={n1}'
                f'   Point3={n2}   Point4={n3}'
            )
        _write_section(fh, "AREA OBJECT CONNECTIVITIES", area_rows)

        # Area slab assignments
        area_assign = [
            f'Area={j + 1}   Slab="MAT"' for j in range(len(elements))
        ]
        _write_section(fh, "AREA OBJECT SLAB ASSIGNMENTS", area_assign)

        # Area soil assignments (surface springs)
        soil_assign = [
            f'Area={j + 1}   Soil="SOIL"' for j in range(len(elements))
        ]
        _write_section(fh, "AREA OBJECT SOIL ASSIGNMENTS", soil_assign)

        # Load patterns
        _write_section(fh, "LOAD PATTERNS", [
            'LoadPat="DEAD"   DesignType="DEAD"   SelfWtMult=1.0',
            'LoadPat="LIVE"   DesignType="LIVE"   SelfWtMult=0',
        ])

        # Distributed surface load (DEAD)
        if uniform_pressure != 0.0:
            udl_rows = [
                f'Area={j + 1}   LoadPat="DEAD"   Dir="Z"   '
                f'UnifLoad={-uniform_pressure}'  # SAFE: +Z up
                for j in range(len(elements))
            ]
            _write_section(fh, "AREA OBJECT UNIFORM LOADS", udl_rows)

        # Column point loads
        if column_loads:
            # Snap each column to the nearest mesh node
            point_load_rows = []
            for (cx, cy, P, Mx, My, name) in column_loads:
                d2 = (nodes_xy[:, 0] - cx) ** 2 + (nodes_xy[:, 1] - cy) ** 2
                nid = int(d2.argmin()) + 1
                row = (
                    f'Point={nid}   LoadPat="DEAD"   '
                    f'FX=0   FY=0   FZ={-P}   MX={Mx}   MY={My}   MZ=0'
                )
                if name:
                    row += f'   Label="{name}"'
                point_load_rows.append(row)
            _write_section(fh, "POINT LOAD ASSIGNMENTS", point_load_rows)

        fh.write("\nEND\n")

    return output_path


def export_mat_to_safe(
    solver: "MatFoundationSolver",
    output_path: str,
    fck_MPa: float = 30.0,
    model_name: str = "Mat",
) -> str:
    """Convenience wrapper: dump a fully-built `MatFoundationSolver` to .s2k."""
    cols = [
        (c.x, c.y, c.P, c.Mx, c.My, c.name) for c in solver._column_loads
    ]
    return export_safe_s2k(
        nodes_xy=solver.nodes_xy,
        elements=solver.elements,
        column_loads=cols,
        uniform_pressure=solver._uniform_pressure,
        thickness=solver.thickness,
        fck_MPa=fck_MPa,
        k_s_kN_m3=solver.k_s,
        output_path=output_path,
        model_name=model_name,
    )
